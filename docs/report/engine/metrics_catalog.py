def normalize_key(key):
    if not isinstance(key, str):
        return ""
    return "".join(ch for ch in key.strip().lower() if ch.isalnum())


METRIC_BY_NORM = {normalize_key(key): key for key in METRIC_BY_KEY}


def find_module_for_key(key):
    norm = normalize_key(key)
    for module, keys in MODULE_CONTAINER_KEYS.items():
        if norm in keys or key in keys:
            return module
    return None


def resolve_metric(key, context=None):
    norm = normalize_key(key)
    hit = METRIC_ALIASES.get(norm)
    if hit is not None:
        canonical, module = hit
        if context and module != context:
            # Generic metric names are allowed when the parent key already
            # established the module, but keep context-local aliases first.
            local = CONTEXT_ALIASES.get(context, {}).get(norm)
            if local:
                return local, context
            return canonical, module
        return canonical, module
    if context and norm in CONTEXT_ALIASES.get(context, {}):
        canonical = CONTEXT_ALIASES[context][norm]
        return canonical, context
    if norm in METRIC_BY_NORM:
        canonical = METRIC_BY_NORM[norm]
        module = METRIC_BY_KEY[canonical][0]
        if not context or module == context:
            return canonical, module
    return None, None


def metric_definition(canonical):
    return METRIC_BY_KEY.get(canonical)
